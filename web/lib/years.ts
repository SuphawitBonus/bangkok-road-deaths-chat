export const BE_OFFSET = 543

/** ปีแรกที่มีข้อมูล (ค.ศ. 2011 = พ.ศ. 2554) */
export const DATA_YEAR_MIN = 2011

/**
 * ปีสุดท้ายที่ข้อมูลครบ (ค.ศ. 2024 = พ.ศ. 2567) — ปี 2025 และ 2026 ยังทยอยเข้า จึงไม่เปิดให้เลือก
 * ค่าสองตัวนี้ถูกตรวจกับตารางจริงใน `npm run db:check` ถ้าข้อมูลเปลี่ยนแล้วลืมแก้ที่นี่ จะเห็นทันที
 */
export const DATA_YEAR_MAX_COMPLETE = 2024

export const toBuddhistYear = (commonEra: number): number => commonEra + BE_OFFSET

export const toCommonEra = (buddhistEra: number): number => buddhistEra - BE_OFFSET
