-- view `deaths` — หน้าเดียวที่ AI มองเห็น
--
-- กฎทำความสะอาดทุกข้ออยู่ในไฟล์นี้ที่เดียว อ้างอิงจากการสำรวจข้อมูลใน
-- analysis/bangkok-road-deaths.ipynb ของโปรเจกต์ NextTraffic
--
-- สิ่งที่ทำ
--   1. พิกัด 479 แถวกรอกสลับคอลัมน์ (lat ไปอยู่ที่ lng) → ตรวจจาก lat > 90 แล้วสลับคืน
--   2. พิกัด 0,0 จำนวน 2 แถว และพิกัดนอกกรอบกรุงเทพฯ → ทำเป็น NULL
--   3. อายุเกิน 110 ปี จำนวน 31 แถว (สูงสุด 149) → ทำเป็น NULL
--   4. helmet / seatbelt ว่าง 100% → ไม่ส่งต่อเข้า view
--   5. record_date_raw รูปแบบไม่คงที่และปนปี พ.ศ. → ไม่ส่งต่อเข้า view
--   6. เพิ่มคอลัมน์ธง (is_complete_year, vehicle_known, sex_known, has_location)
--      เพื่อให้เขียน WHERE ได้ถูกต้องโดยไม่ต้องจำกฎเอง
--   7. crash_district 310 แถวกรอกชื่อเขตโดยไม่มีคำว่า "เขต" นำหน้า ('บางขุนเทียน'
--      กับ 'เขตบางขุนเทียน') ทำให้ 49 เขตกลายเป็น 97 ค่า → เติม "เขต" ให้ครบ
--      ตรวจแล้วว่าทุกชื่อที่ไม่มีคำนำหน้าตรงกับชื่อที่มีคำนำหน้าสักชื่อเสมอ
--
-- สิ่งที่ไม่ทำ: ไม่เติมค่าที่หายไป ไม่เดาแทน แถวที่ข้อมูลขาดยังอยู่ครบ
-- เพียงแต่คอลัมน์ที่ใช้ไม่ได้เป็น NULL เพื่อให้นับได้ว่าหายไปเท่าไร

CREATE OR REPLACE VIEW app.deaths AS
WITH coords_fixed AS (
    SELECT
        r.*,
        -- ละติจูดของจริงอยู่ราว 13 ส่วนลองจิจูดอยู่ราว 100 ค่าที่เกิน 90 ในช่อง
        -- ละติจูดจึงเป็นไปไม่ได้ และหมายความว่ากรอกสลับคอลัมน์ ไม่ใช่ข้อมูลเสีย
        CASE WHEN r.latitude > 90 AND r.longitude < 90
             THEN r.longitude ELSE r.latitude  END AS lat_fixed,
        CASE WHEN r.latitude > 90 AND r.longitude < 90
             THEN r.latitude  ELSE r.longitude END AS lng_fixed
    FROM app.deaths_raw r
),
bounded AS (
    SELECT
        c.*,
        (c.lat_fixed BETWEEN 13.4 AND 14.0
         AND c.lng_fixed BETWEEN 100.2 AND 100.95) AS inside_bangkok
    FROM coords_fixed c
)
SELECT
    id,
    year_be,
    (year_be NOT IN (2568, 2569))                    AS is_complete_year,

    died_on,
    EXTRACT(YEAR  FROM died_on)::int                 AS died_year,
    EXTRACT(MONTH FROM died_on)::int                 AS died_month,
    EXTRACT(ISODOW FROM died_on)::int                AS died_isodow,

    record_time,
    EXTRACT(HOUR FROM record_time)::int              AS record_hour,

    CASE WHEN age BETWEEN 0 AND 110 THEN age END     AS age,

    sex,
    (sex IS DISTINCT FROM 'ไม่ระบุ')                  AS sex_known,

    vehicle,
    (vehicle IS DISTINCT FROM 'ไม่ระบุพาหนะ')          AS vehicle_known,

    nullif(residence_district, '')                   AS residence_district,
    CASE WHEN nullif(crash_district, '') IS NULL     THEN NULL
         WHEN crash_district LIKE 'เขต%'              THEN crash_district
         ELSE 'เขต' || crash_district END             AS crash_district,
    nullif(nationality, '')                          AS nationality,
    nullif(icd10_code, '')                           AS icd10_code,

    CASE WHEN inside_bangkok THEN lat_fixed END      AS latitude,
    CASE WHEN inside_bangkok THEN lng_fixed END      AS longitude,
    coalesce(inside_bangkok, false)                  AS has_location
FROM bounded;


